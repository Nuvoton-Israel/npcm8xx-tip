/*---------------------------------------------------------------------------------------------------------*/
/* Function:        TIMER_Tick_L                                                                           */
/*                                                                                                         */
/* Parameters:                                                                                             */
/*                  ch  - Number of channel                                                                */
/*                                                                                                         */
/* Returns:                                                                                                */
/* Side effects:                                                                                           */
/* Description:                                                                                            */
/*                  This routine handles timer tick                                                        */
/*---------------------------------------------------------------------------------------------------------*/
static void TIMER_Tick_L (TIMER_CHANNEL_T ch)
{
    UINT            i           = 0;
    TIMER_T*        timer       = &TIMER_Channel_l[ch];
    TIMER_CFG_T*    timerCfg    = &timer->timerCfg;
    UINT            saveInt     = 0;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Check error condition                                                                               */
    /*-----------------------------------------------------------------------------------------------------*/
    ASSERT(ch < TIMER_NUM_OF_CHANNELS);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Check if timer enabled                                                                              */
    /*-----------------------------------------------------------------------------------------------------*/
    ASSERT(timer->enabled);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Disable interrupts                                                                                  */
    /*-----------------------------------------------------------------------------------------------------*/
    INTERRUPTS_SAVE_DISABLE(saveInt);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Handle tick                                                                                         */
    /*-----------------------------------------------------------------------------------------------------*/
    timer->tick++;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Handle events                                                                                       */
    /*-----------------------------------------------------------------------------------------------------*/
    for (i=0; i<TIMER_NUM_OF_EVENTS_PER_CHANNEL; ++i)
    {
        TIMER_EVENT_T* event = &timerCfg->events[i];

        /*-------------------------------------------------------------------------------------------------*/
        /* Check if event is enabled                                                                       */
        /*-------------------------------------------------------------------------------------------------*/
        if (event->enabled)
        {
            /*---------------------------------------------------------------------------------------------*/
            /* Check if we need to trigger the event                                                       */
            /*---------------------------------------------------------------------------------------------*/
            if (timer->tick >= event->targetTick)
            {
                /*-----------------------------------------------------------------------------------------*/
                /* Trigger event                                                                           */
                /*-----------------------------------------------------------------------------------------*/
                EXECUTE_FUNC(event->eventCallback, (event->eventParam));

                /*-----------------------------------------------------------------------------------------*/
                /* Handle one time events                                                                  */
                /*-----------------------------------------------------------------------------------------*/
                if (event->eventType == TIMER_EVENT_EXEC_SINGLE)
                {
                    /*-------------------------------------------------------------------------------------*/
                    /* Event is single type, disable it                                                    */
                    /*-------------------------------------------------------------------------------------*/
                    TIMER_RemoveEventWrapper_L(timerCfg, i);
                }
            }
        }
    }

    /*-----------------------------------------------------------------------------------------------------*/
    /* Handle one-time timers                                                                              */
    /*-----------------------------------------------------------------------------------------------------*/
    if (timer->timerCfg.opMode == TIMER_OPMODE_ONESHOT_MODE)
    {
        /*-------------------------------------------------------------------------------------------------*/
        /* Timer is one-shot. Disable it                                                                   */
        /*-------------------------------------------------------------------------------------------------*/
        (void)TIMER_Stop(ch);
    }

    /*-----------------------------------------------------------------------------------------------------*/
    /* Restore interrupts                                                                                  */
    /*-----------------------------------------------------------------------------------------------------*/
    INTERRUPTS_RESTORE(saveInt);
}


