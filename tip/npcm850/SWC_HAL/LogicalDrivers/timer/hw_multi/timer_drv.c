/*---------------------------------------------------------------------------------------------------------*/
/* Function:        TIMER_GetTime                                                                          */
/*                                                                                                         */
/* Parameters:                                                                                             */
/*                  ch  - Timer channel                                                                    */
/*                                                                                                         */
/* Returns:         DEFS_STATUS_OK if no errors occurred, or DEFS_STATUS_x on error                        */
/* Side effects:                                                                                           */
/* Description:                                                                                            */
/*                  This routine returns passed time (from start/reset) in timer units                     */
/*---------------------------------------------------------------------------------------------------------*/
UINT32 TIMER_GetTime(TIMER_CHANNEL_T ch)
{
    UINT32      time    = 0;
    TIMER_T*    timer   = &TIMER_Channel_l[ch];
    UINT        saveInt = 0;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Check error condition                                                                               */
    /*-----------------------------------------------------------------------------------------------------*/
    ASSERT(ch < TIMER_NUM_OF_CHANNELS);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Disable interrupts                                                                                  */
    /*-----------------------------------------------------------------------------------------------------*/
    INTERRUPTS_SAVE_DISABLE(saveInt);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Check if enabled                                                                                    */
    /*-----------------------------------------------------------------------------------------------------*/
    if (!timer->enabled)
    {
        ASSERT(FALSE);
        time = (UINT32)-1;
    }
    else
    {
        /*-------------------------------------------------------------------------------------------------*/
        /* Calculate time in timer units                                                                   */
        /*-------------------------------------------------------------------------------------------------*/
        time = timer->tick * timer->timerCfg.tickPeriod;
    }

    /*-----------------------------------------------------------------------------------------------------*/
    /* Restore interrupts                                                                                  */
    /*-----------------------------------------------------------------------------------------------------*/
    INTERRUPTS_RESTORE(saveInt);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Return time in timer units                                                                          */
    /*-----------------------------------------------------------------------------------------------------*/
    return time;
}

/*---------------------------------------------------------------------------------------------------------*/
/* Function:        TIMER_Delay                                                                            */
/*                                                                                                         */
/* Parameters:                                                                                             */
/*                  time    - Amount of time to wait (in timer units)                                      */
/*                                                                                                         */
/* Returns:         none                                                                                   */
/* Side effects:                                                                                           */
/* Description:                                                                                            */
/*                  This routine executes blocking delay for given amount of time (in timer units)         */
/*---------------------------------------------------------------------------------------------------------*/
void TIMER_Delay(UINT32 time)
{
    /*-----------------------------------------------------------------------------------------------------*/
    /* Get current time                                                                                    */
    /*-----------------------------------------------------------------------------------------------------*/
    UINT32 currentTime = TIMER_GetTime(TIMER_DELAY_CHANNEL);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Wait till required amount of time will pass                                                         */
    /*-----------------------------------------------------------------------------------------------------*/
    while (TIMER_GetTime(TIMER_DELAY_CHANNEL) < (currentTime + time)) {}
}


