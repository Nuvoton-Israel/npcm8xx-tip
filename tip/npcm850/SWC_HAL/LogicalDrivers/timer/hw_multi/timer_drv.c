/*---------------------------------------------------------------------------------------------------------*/
/* Function:        TIMER_Init                                                                             */
/*                                                                                                         */
/* Parameters:      none                                                                                   */
/* Returns:         none                                                                                   */
/* Side effects:                                                                                           */
/* Description:                                                                                            */
/*                  This routine initializes the TIMER module                                              */
/*---------------------------------------------------------------------------------------------------------*/
void TIMER_Init(void)
{
    UINT16 i;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Initialize timer channels                                                                           */
    /*-----------------------------------------------------------------------------------------------------*/
    for (i=0; i<TIMER_NUM_OF_CHANNELS; ++i)
    {
        /*-------------------------------------------------------------------------------------------------*/
        /* Clear timer structure                                                                           */
        /*-------------------------------------------------------------------------------------------------*/
        memset(&TIMER_Channel_l[i], 0, sizeof(TIMER_T));

        /*-------------------------------------------------------------------------------------------------*/
        /* Initialize Timer Operations                                                                     */
        /*-------------------------------------------------------------------------------------------------*/
        TIMER_Channel_l[i].timerOps = &TIMER_HW_Ops_l[TIMER_Allocation_l[i].hwType];
    }
}

/*---------------------------------------------------------------------------------------------------------*/
/* Function:        TIMER_Open                                                                             */
/*                                                                                                         */
/* Parameters:                                                                                             */
/*                  ch          - Timer channel                                                            */
/*                  unit        - Timer working units (sec/milli/micro/nano)                               */
/*                  tickPeriod  - Period between two ticks (in timer units)                                */
/*                  opMode      - Operation mode                                                           */
/*                                                                                                         */
/* Returns:         DEFS_STATUS_OK if no errors occurred, or DEFS_STATUS_x on error                        */
/* Side effects:                                                                                           */
/* Description:                                                                                            */
/*                  This routine opens a specific timer channel in given operation mode                    */
/*---------------------------------------------------------------------------------------------------------*/
DEFS_STATUS TIMER_Open(TIMER_CHANNEL_T ch, TIMER_UNIT_T unit, UINT32 tickPeriod, TIMER_OPMODE_T opMode)
{
    UINT16              i           = 0;
    TIMER_T*            timer       = NULL;
    const TIMER_OPS_T*  timerOps    = NULL;
    TIMER_CFG_T*        timerCfg    = NULL;
    DEFS_STATUS         ret         = DEFS_STATUS_OK;
    UINT                saveInt     = 0;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Check error condition                                                                               */
    /*-----------------------------------------------------------------------------------------------------*/
    ASSERT(ch < TIMER_NUM_OF_CHANNELS);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Disable interrupts                                                                                  */
    /*-----------------------------------------------------------------------------------------------------*/
    INTERRUPTS_SAVE_DISABLE(saveInt);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Get timer                                                                                           */
    /*-----------------------------------------------------------------------------------------------------*/
    timer       = &TIMER_Channel_l[ch];
    timerOps    = timer->timerOps;
    timerCfg    = &timer->timerCfg;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Initialize Timer structure                                                                          */
    /*-----------------------------------------------------------------------------------------------------*/
    timer->tick             = 0;
    timerCfg->unit          = unit;
    timerCfg->opMode        = opMode;
    timerCfg->tickPeriod    = tickPeriod;
    timerCfg->eventCount    = 0;

    for (i=0; i<TIMER_NUM_OF_EVENTS_PER_CHANNEL; ++i)
    {
        timerCfg->events[i].enabled = FALSE;
    }

    /*-----------------------------------------------------------------------------------------------------*/
    /* Mark timer enabled                                                                                  */
    /*-----------------------------------------------------------------------------------------------------*/
    timer->enabled    = TRUE;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Execute open callback                                                                               */
    /*-----------------------------------------------------------------------------------------------------*/
    ret = TIMER_EXECUTE_CALLBACK(timerOps->Open, ch);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Re-enable interrupts                                                                                */
    /*-----------------------------------------------------------------------------------------------------*/
    INTERRUPTS_RESTORE(saveInt);

    return ret;
}

/*---------------------------------------------------------------------------------------------------------*/
/* Function:        TIMER_Close                                                                            */
/*                                                                                                         */
/* Parameters:                                                                                             */
/*                  ch  - Timer channel                                                                    */
/*                                                                                                         */
/* Returns:         DEFS_STATUS_OK if no errors occurred, or DEFS_STATUS_x on error                        */
/* Side effects:                                                                                           */
/* Description:                                                                                            */
/*                  This routine closes timer channel                                                      */
/*---------------------------------------------------------------------------------------------------------*/
DEFS_STATUS TIMER_Close(TIMER_CHANNEL_T ch)
{
    TIMER_T*            timer       = NULL;
    const TIMER_OPS_T*  timerOps    = NULL;
    DEFS_STATUS         ret         = DEFS_STATUS_OK;
    UINT                saveInt     = 0;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Check error condition                                                                               */
    /*-----------------------------------------------------------------------------------------------------*/
    ASSERT(ch < TIMER_NUM_OF_CHANNELS);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Disable interrupts                                                                                  */
    /*-----------------------------------------------------------------------------------------------------*/
    INTERRUPTS_SAVE_DISABLE(saveInt);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Get timer                                                                                           */
    /*-----------------------------------------------------------------------------------------------------*/
    timer       = &TIMER_Channel_l[ch];
    timerOps    = timer->timerOps;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Disable timer                                                                                       */
    /*-----------------------------------------------------------------------------------------------------*/
    timer->enabled  = FALSE;
    timer->tick     = 0;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Execute close callback                                                                              */
    /*-----------------------------------------------------------------------------------------------------*/
    ret = TIMER_EXECUTE_CALLBACK(timerOps->Close, ch);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Re-enable interrupts                                                                                */
    /*-----------------------------------------------------------------------------------------------------*/
    INTERRUPTS_RESTORE(saveInt);

    return ret;
}

/*---------------------------------------------------------------------------------------------------------*/
/* Function:        TIMER_SetTimerEvent                                                                    */
/*                                                                                                         */
/* Parameters:                                                                                             */
/*                  ch                  - Timer channel to use                                             */
/*                  periodToTrigger     - Period of time (in timer units) till event is triggered          */
/*                  eventType           - Event execution type                                             */
/*                  timerCallback       - Timer event                                                      */
/*                  timerCallbackArg    - Timer event parameter                                            */
/*                                                                                                         */
/* Returns:         DEFS_STATUS_OK if no errors occurred, or DEFS_STATUS_x on error                        */
/* Side effects:                                                                                           */
/* Description:                                                                                            */
/*                  This routine sets a new event for given timer channel, multiple events can be set per  */
/*                  single timer channel. (Number of multiple events per channel defined by                */
/*                  TIMER_NUM_OF_EVENTS_PER_CHANNEL #define)                                               */
/*---------------------------------------------------------------------------------------------------------*/
DEFS_STATUS TIMER_SetTimerEvent(TIMER_CHANNEL_T     ch,
                                UINT32              periodToTrigger,
                                TIMER_EVENT_EXEC_T  eventType,
                                TIMER_CALLBACK_T    timerCallback,
                                void*               timerCallbackArg)
{
    UINT                i       = 0;
    TIMER_T*            timer   = &TIMER_Channel_l[ch];
    TIMER_EVENT_T*      event   = NULL;
    DEFS_STATUS         ret     = DEFS_STATUS_OK;
    volatile UINT       saveInt = 0;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Check error condition                                                                               */
    /*-----------------------------------------------------------------------------------------------------*/
    ASSERT(ch < TIMER_NUM_OF_CHANNELS);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Disable interrupts                                                                                  */
    /*-----------------------------------------------------------------------------------------------------*/
    INTERRUPTS_SAVE_DISABLE(saveInt);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Check if timer is enabled                                                                           */
    /*-----------------------------------------------------------------------------------------------------*/
    if (!timer->enabled)
    {
        ret = DEFS_STATUS_SYSTEM_IN_INCORRECT_STATE;
        /*lint -e{801}                                                                                     */
        goto exit;
    }

    /*-----------------------------------------------------------------------------------------------------*/
    /* Check number of allocated events                                                                    */
    /*-----------------------------------------------------------------------------------------------------*/
    if (timer->timerCfg.eventCount == TIMER_NUM_OF_EVENTS_PER_CHANNEL)
    {
        /*-------------------------------------------------------------------------------------------------*/
        /* No space for new event                                                                          */
        /*-------------------------------------------------------------------------------------------------*/
        ret = DEFS_STATUS_PARAMETER_OUT_OF_RANGE;
        /*lint -e{801}                                                                                     */
        goto exit;
    }

    /*-----------------------------------------------------------------------------------------------------*/
    /* Find empty slot for event allocation                                                                */
    /*-----------------------------------------------------------------------------------------------------*/
    for (i=0; i<TIMER_NUM_OF_EVENTS_PER_CHANNEL; ++i)
    {
        /*-------------------------------------------------------------------------------------------------*/
        /* Check if we have empty slot                                                                     */
        /*-------------------------------------------------------------------------------------------------*/
        if (!timer->timerCfg.events[i].enabled)
        {
            /*---------------------------------------------------------------------------------------------*/
            /* Empty slot found                                                                            */
            /*---------------------------------------------------------------------------------------------*/
            break;
        }
    }

    /*-----------------------------------------------------------------------------------------------------*/
    /* Allocate new event                                                                                  */
    /*-----------------------------------------------------------------------------------------------------*/
    if (i < TIMER_NUM_OF_EVENTS_PER_CHANNEL)
    {
        timer->timerCfg.eventCount++;
        event = &timer->timerCfg.events[i];
        event->eventCallback    = timerCallback;
        event->eventParam       = timerCallbackArg;
        event->eventType        = eventType;
        event->targetTick       = timer->tick + TIMER_TIME_TO_TICKS(periodToTrigger, timer);
        event->enabled          = TRUE;
    }
    else
    {
        ret = DEFS_STATUS_FAIL;
    }

exit:
    /*-----------------------------------------------------------------------------------------------------*/
    /* Re-enable interrupts                                                                                */
    /*-----------------------------------------------------------------------------------------------------*/
    INTERRUPTS_RESTORE(saveInt);

    return ret;
}

/*---------------------------------------------------------------------------------------------------------*/
/* Function:        TIMER_RemoveTimerEvent                                                                 */
/*                                                                                                         */
/* Parameters:                                                                                             */
/*                  ch              - Timer channel                                                        */
/*                  timerCallback   - Timer event to remove                                                */
/*                                                                                                         */
/* Returns:         DEFS_STATUS_OK if no errors occurred, or DEFS_STATUS_x on error                        */
/* Side effects:                                                                                           */
/* Description:                                                                                            */
/*                  This routine removes given timer event                                                 */
/*---------------------------------------------------------------------------------------------------------*/
DEFS_STATUS TIMER_RemoveTimerEvent(TIMER_CHANNEL_T ch, TIMER_CALLBACK_T timerCallback)
{
    UINT            i           = 0;
    TIMER_CFG_T*    timerCfg    = &TIMER_Channel_l[ch].timerCfg;
    DEFS_STATUS     ret         = DEFS_STATUS_INVALID_PARAMETER;
    UINT            saveInt     = 0;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Check error condition                                                                               */
    /*-----------------------------------------------------------------------------------------------------*/
    ASSERT(ch < TIMER_NUM_OF_CHANNELS);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Disable interrupts                                                                                  */
    /*-----------------------------------------------------------------------------------------------------*/
    INTERRUPTS_SAVE_DISABLE(saveInt);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Check all events                                                                                    */
    /*-----------------------------------------------------------------------------------------------------*/
    for (i=0; i<TIMER_NUM_OF_EVENTS_PER_CHANNEL; ++i)
    {
        BOOLEAN eventFound;

        /*-------------------------------------------------------------------------------------------------*/
        /* Check if event was found                                                                        */
        /*-------------------------------------------------------------------------------------------------*/
        eventFound = timerCfg->events[i].enabled && (timerCfg->events[i].eventCallback == timerCallback);

        /*-------------------------------------------------------------------------------------------------*/
        /* If we found our event                                                                           */
        /*-------------------------------------------------------------------------------------------------*/
        if (eventFound)
        {
            /*---------------------------------------------------------------------------------------------*/
            /* Disable event                                                                               */
            /*---------------------------------------------------------------------------------------------*/
            TIMER_RemoveEventWrapper_L(timerCfg, i);

            /*---------------------------------------------------------------------------------------------*/
            /* Mark that we finished successfully                                                          */
            /*---------------------------------------------------------------------------------------------*/
            ret = DEFS_STATUS_OK;

            break;
        }
    }

    /*-----------------------------------------------------------------------------------------------------*/
    /* Re-enable interrupts                                                                                */
    /*-----------------------------------------------------------------------------------------------------*/
    INTERRUPTS_RESTORE(saveInt);

    return ret;
}

/*---------------------------------------------------------------------------------------------------------*/
/* Function:        TIMER_ClearEvents                                                                      */
/*                                                                                                         */
/* Parameters:                                                                                             */
/*                  ch  - Timer channel                                                                    */
/*                                                                                                         */
/* Returns:                                                                                                */
/* Side effects:                                                                                           */
/* Description:                                                                                            */
/*                  This routine cleans all events from given channel                                      */
/*---------------------------------------------------------------------------------------------------------*/
DEFS_STATUS TIMER_ClearEvents(TIMER_CHANNEL_T ch)
{
    UINT            saveInt     = 0;
    UINT            i           = 0;
    TIMER_CFG_T*    timerCfg    = &TIMER_Channel_l[ch].timerCfg;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Check error condition                                                                               */
    /*-----------------------------------------------------------------------------------------------------*/
    ASSERT(ch < TIMER_NUM_OF_CHANNELS);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Disable interrupts                                                                                  */
    /*-----------------------------------------------------------------------------------------------------*/
    INTERRUPTS_SAVE_DISABLE(saveInt);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Clear all events                                                                                    */
    /*-----------------------------------------------------------------------------------------------------*/
    for (i=0; i<TIMER_NUM_OF_EVENTS_PER_CHANNEL; ++i)
    {
        TIMER_EVENT_T* event = &timerCfg->events[i];

        memset(event, 0, sizeof(TIMER_EVENT_T));
    }

    /*-----------------------------------------------------------------------------------------------------*/
    /* Clear event number                                                                                  */
    /*-----------------------------------------------------------------------------------------------------*/
    timerCfg->eventCount = 0;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Restore interrupts                                                                                  */
    /*-----------------------------------------------------------------------------------------------------*/
    INTERRUPTS_RESTORE(saveInt);

    return DEFS_STATUS_OK;
}

