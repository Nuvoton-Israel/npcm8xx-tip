#ifndef _MPU_REGS_H
#define _MPU_REGS_H

#include __CHIP_H_FROM_DRV()

/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/
/*                                              MPU REGISTERS                                              */
/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/
#define MPU_TYPE           (MPU_BASE_ADDR + 0x00),         MPU_ACCESS, 32
#define MPU_CTRL           (MPU_BASE_ADDR + 0x04),         MPU_ACCESS, 32
#define MPU_RNR            (MPU_BASE_ADDR + 0x08),         MPU_ACCESS, 32
#define MPU_RBAR           (MPU_BASE_ADDR + 0x0C),         MPU_ACCESS, 32
#define MPU_RASR           (MPU_BASE_ADDR + 0x10),         MPU_ACCESS, 32
#define MPU_RBAR_A(n)      (MPU_BASE_ADDR + 0x14 + 8 * n), MPU_ACCESS, 32
#define MPU_RASR_A(n)      (MPU_BASE_ADDR + 0x18 + 8 * n), MPU_ACCESS, 32

/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/
/*                                           MPU REGISTER FIELDS                                           */
/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/

/*---------------------------------------------------------------------------------------------------------*/
/* MPU_TYPE register fields                                                                                */
/*---------------------------------------------------------------------------------------------------------*/
#define MPU_TYPE_SEPARATE         0,  1
#define MPU_TYPE_DREGION          8,  8
#define MPU_TYPE_IREGION          16, 8

/*---------------------------------------------------------------------------------------------------------*/
/* MPU_CTRL register fields                                                                                */
/*---------------------------------------------------------------------------------------------------------*/
#define MPU_CTRL_ENABLE           0,  1
#define MPU_CTRL_HFNMIENA         1,  1
#define MPU_CTRL_PRIVDEFENA       2,  1

/*---------------------------------------------------------------------------------------------------------*/
/* MPU_RNR register fields                                                                                 */
/*---------------------------------------------------------------------------------------------------------*/
#define MPU_RNR_REGION            0,  8

/*---------------------------------------------------------------------------------------------------------*/
/* MPU_RBAR register fields                                                                                */
/*---------------------------------------------------------------------------------------------------------*/
#define MPU_RBAR_REGION           0,  4
#define MPU_RBAR_VALID            4,  1
#define MPU_RBAR_ADDR(n)          n, (32-n)

/*---------------------------------------------------------------------------------------------------------*/
/* MPU_RASR register fields                                                                                */
/*---------------------------------------------------------------------------------------------------------*/
#define MPU_RASR_ENABLE           0,  1
#define MPU_RASR_SIZE             1,  5
#define MPU_RASR_SRD              8,  8
#define MPU_RASR_B_C_S_TEX        16, 6
#define MPU_RASR_AP               24, 3
#define MPU_RASR_XN               28, 1

#endif /* _OTPI_REGS_H */

