/*---------------------------------------------------------------------------------------------------------*/
/* Timer event struct                                                                                      */
/*---------------------------------------------------------------------------------------------------------*/
typedef struct
{
    BOOLEAN             enabled;
    UINT32              targetTick;
    TIMER_EVENT_EXEC_T  eventType;
    TIMER_CALLBACK_T    eventCallback;
    void*               eventParam;
} TIMER_EVENT_T;

/*---------------------------------------------------------------------------------------------------------*/
/* Timer configuration                                                                                     */
/*---------------------------------------------------------------------------------------------------------*/
typedef struct
{
    TIMER_UNIT_T        unit;
    UINT32              tickPeriod;
    TIMER_OPMODE_T      opMode;
    UINT16              eventCount;
    TIMER_EVENT_T       events[TIMER_NUM_OF_EVENTS_PER_CHANNEL];
} TIMER_CFG_T;

/*---------------------------------------------------------------------------------------------------------*/
/* Timer operations                                                                                        */
/*---------------------------------------------------------------------------------------------------------*/
typedef struct
{
    DEFS_STATUS (*Open)     (TIMER_CHANNEL_T ch);
    DEFS_STATUS (*Close)    (TIMER_CHANNEL_T ch);
    DEFS_STATUS (*Start)    (TIMER_CHANNEL_T ch);
    DEFS_STATUS (*Stop)     (TIMER_CHANNEL_T ch);
    UINT32      (*SubTick)  (TIMER_CHANNEL_T ch);
} TIMER_OPS_T;


/*---------------------------------------------------------------------------------------------------------*/
/* Timer structure                                                                                         */
/*---------------------------------------------------------------------------------------------------------*/
typedef struct
{
    TIMER_CFG_T         timerCfg;
    const TIMER_OPS_T*  timerOps;
    BOOLEAN             enabled;
    BOOLEAN             started;
    UINT32              tick;
} TIMER_T;

