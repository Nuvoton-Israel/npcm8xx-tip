/*---------------------------------------------------------------------------------------------------------*/
/* Callback execution utility                                                                              */
/*---------------------------------------------------------------------------------------------------------*/
#define TIMER_EXECUTE_CALLBACK(callback, cfg)           ((callback != NULL) ? callback(cfg) :  DEFS_STATUS_OK)

/*---------------------------------------------------------------------------------------------------------*/
/* Number of channels                                                                                      */
/*---------------------------------------------------------------------------------------------------------*/
#define TIMER_NUM_OF_CHANNELS                           ARRAY_SIZE(TIMER_Allocation_l)

/*---------------------------------------------------------------------------------------------------------*/
/* Conversion from TIME to TICKS                                                                           */
/*---------------------------------------------------------------------------------------------------------*/
#define TIMER_TIME_TO_TICKS(time, timer)                (DIV_ROUND(time, timer->timerCfg.tickPeriod))

/*---------------------------------------------------------------------------------------------------------*/
/* Conversion from TICKS to TIME                                                                           */
/*---------------------------------------------------------------------------------------------------------*/
#define TIMER_TICKS_TO_TIME(ticks, timer)               ((ticks) * (timer->timerCfg.tickPeriod))

